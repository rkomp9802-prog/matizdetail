function normalize(text) {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const { rows } = await db.execute('select normalized_question from questions');
const existing = new Set(rows.map((r) => String(r.normalized_question)));

let added = 0;
let skipped = 0;

async function insert({ q, k, a }) {
  const normalized = normalize(q);
  if (existing.has(normalized)) {
    skipped++;
    return;
  }

  const now = new Date().toISOString();
  await db.execute({
    sql: `insert into questions
            (id, question, normalized_question, answer, gemini_answer, keywords, status, asked_count, created_at, answered_at)
          values (?, ?, ?, ?, NULL, ?, ?, 0, ?, ?)`,
    args: [
      crypto.randomUUID(),
      q,
      normalized,
      a ?? null,
      k,
      a ? 'answered' : 'pending',
      now,
      a ? now : null,
    ],
  });

  existing.add(normalized);
  added++;
}

for (const entry of answered) await insert(entry);
for (const entry of pending) await insert({ ...entry, a: null });

console.log(`Добавлено: ${added}, пропущено (уже было): ${skipped}`);
